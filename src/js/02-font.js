const Font = {
  LH: 14,               // alto de línea
  glyphs: {},
  cache: {},
  colors: {
    dark: ['#3c3434', '#d6cbb3'],
    light: ['#fbf7ee', '#4a3a52'],
    gold: ['#f8d458', '#5c3210'],
    red: ['#c8302a', '#efc4b0'],
    grey: ['#8c8478', '#e6dcc6'],
    blue: ['#2c56b4', '#c4d4f2'],
    white: ['#ffffff', '#20182a'],
    ink: ['#2a2030', null],
    dim: ['#a898bc', '#1a1424'],
  },
  init() {
    for (const ch in GLYPHS) {
      const rows = GLYPHS[ch];
      const pts = [];
      let w = 0;
      rows.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') { pts.push([x, y]); w = Math.max(w, x + 1); } });
      if (ch === ' ') w = 3;
      this.glyphs[ch] = { pts, w: Math.max(w, rows[0].length === 1 ? 1 : w) };
      if (!pts.length && ch !== ' ') this.glyphs[ch].w = rows[0].length;
    }
    this.glyphs[' '] = { pts: [], w: 3 };
    for (const ch in ACCENTS) {
      const [base, kind] = ACCENTS[ch];
      const g = this.glyphs[base];
      const upper = base === base.toUpperCase() && base !== 'ı';
      const r0 = upper ? -2 : -1, r1 = upper ? -1 : 0;
      let pts = g.pts.slice();
      let w = g.w;
      if ((kind === 'circ' || kind === 'diaer') && w < 3) { pts = pts.map(([x, y]) => [x + 1, y]); w = 3; }
      const c = Math.floor((w - 1) / 2);
      if (kind === 'acute') { pts.push([c + 1, r0], [c, r1]); w = Math.max(w, c + 2); }
      else if (kind === 'grave') { pts.push([c, r0], [c + 1, r1]); w = Math.max(w, c + 2); }
      else if (kind === 'circ') {
        if (w === 4) pts.push([1, r0], [2, r0], [0, r1], [3, r1]);
        else pts.push([c, r0], [c - 1, r1], [c + 1, r1]);
      }
      else if (kind === 'tilde') { pts.push([0, r1], [1, r0], [2, r1], [3, r0]); if (w >= 5) pts.push([4, r1]); }
      else if (kind === 'diaer') { const rr = upper ? -2 : 0; pts.push([0, rr], [w - 1, rr]); }
      else if (kind === 'cedil') { pts.push([c + 1, 7], [c, 8]); }
      this.glyphs[ch] = { pts, w };
    }
  },
  glyph(ch) { return this.glyphs[ch] || this.glyphs['?']; },
  canvas(ch, color) {
    const key = color + '|' + ch;
    let c = this.cache[key];
    if (c) return c;
    const g = this.glyph(ch);
    const [fg, sh] = this.colors[color] || this.colors.dark;
    const [cv, x] = mkCanvas(g.w + 1, 14);
    if (sh) for (const [gx, gy] of g.pts) px(x, gx + 1, gy + 3, sh);
    for (const [gx, gy] of g.pts) px(x, gx, gy + 2, fg);
    this.cache[key] = cv;
    return cv;
  },
  width(str) {
    let w = 0;
    for (const ch of str) w += this.glyph(ch).w + 1;
    return Math.max(0, w);
  },
  // y = parte de arriba de la celda (las mayúsculas empiezan en y+2)
  draw(ctx, str, x, y, color = 'dark', scale = 1) {
    let cx = x;
    for (const ch of String(str)) {
      const g = this.glyph(ch);
      if (ch !== ' ') {
        const cv = this.canvas(ch, color);
        if (scale === 1) ctx.drawImage(cv, Math.round(cx), Math.round(y));
        else ctx.drawImage(cv, Math.round(cx), Math.round(y), cv.width * scale, cv.height * scale);
      }
      cx += (g.w + 1) * scale;
    }
    return cx;
  },
  drawRight(ctx, str, xRight, y, color) { this.draw(ctx, str, xRight - this.width(str), y, color); },
  drawCenter(ctx, str, xc, y, color, scale = 1) { this.draw(ctx, str, Math.round(xc - this.width(str) * scale / 2), y, color, scale); },
  wrap(str, maxW) {
    const out = [];
    for (const para of String(str).split('\n')) {
      const words = para.split(' ');
      let line = '';
      for (const w of words) {
        const test = line ? line + ' ' + w : w;
        if (this.width(test) <= maxW || !line) line = test;
        else { out.push(line); line = w; }
      }
      out.push(line);
    }
    return out;
  },
};
