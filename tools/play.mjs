// Prueba automática: juega el principio y guarda capturas de pantalla.
import { chromium } from 'playwright';
const dir = process.argv[2] || '.';
const mobile = process.argv[3] === 'mobile';
const b = await chromium.launch();
const ctx = await b.newContext(mobile ? { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true } : { viewport: { width: 1100, height: 820 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push('pageerror: ' + String(e)));
p.on('console', m => { if (m.type() === 'error' && !/ERR_TUNNEL|fonts/.test(m.text())) errs.push(m.text()); });
await p.goto('file://' + process.cwd() + '/dist/index.html?debug');
await p.waitForFunction(() => window.__SC);
const sleep = ms => p.waitForTimeout(ms);
const key = async (k, n = 1, gap = 260) => { for (let i = 0; i < n; i++) { await p.keyboard.press(k); await sleep(gap); } };
const shot = async name => { await p.screenshot({ path: `${dir}/${name}.png` }); };
const canvasShot = async name => { await p.locator('#screen').screenshot({ path: `${dir}/${name}.png` }); };
const scene = () => p.evaluate(() => window.__SC.Game.scene && window.__SC.Game.scene.constructor.name);
const uiBusy = () => p.evaluate(() => { const s = window.__SC.Game.scene; return !!(s && (s.busy || (s.ui && s.ui.busy))); });

await sleep(800);
await shot('p00_lang');
await key('KeyZ', 1, 900);
await shot('p01_title_page');
await key('KeyZ', 1, 900);
await key('KeyZ', 1, 900);
await canvasShot('p02_select');
await key('ArrowRight', 1, 300);
await key('KeyZ', 1, 900);
await key('KeyZ', 1, 600);
await sleep(300);
await shot('p03_name');
await p.fill('#nameInput', 'Abel');
await p.keyboard.press('Enter');
await sleep(800);
await key('KeyZ', 2, 500);
await sleep(1200);
await canvasShot('p04_intro');
for (let i = 0; i < 30 && (await scene()) !== 'WorldScene'; i++) await key('KeyZ', 1, 450);
await sleep(1500);
await canvasShot('p05_world_madre');
for (let i = 0; i < 20 && (await uiBusy()); i++) await key('KeyZ', 1, 450);
await sleep(400);
await canvasShot('p06_world_free');
// ir junto a Esteban
await p.evaluate(() => { const w = window.__SC.Game.scene; const pl = w.player; pl.x = 17; pl.y = 11; pl.px = 17 * 16; pl.py = 11 * 16; pl.dir = 'right'; });
await sleep(300);
await key('KeyZ', 1, 700);
await canvasShot('p07_esteban');
for (let i = 0; i < 40 && (await scene()) !== 'BattleScene'; i++) await key('KeyZ', 1, 450);
await sleep(1500);
await canvasShot('p08_battle_intro');
await key('KeyZ', 1, 900);
await canvasShot('p09_battle_cmd');
await key('KeyZ', 1, 500);
await canvasShot('p10_battle_moves');
let n = 0;
while ((await scene()) === 'BattleScene' && n < 120) {
  await key('KeyZ', 1, 380);
  n++;
  if (n === 4) await canvasShot('p11_battle_mid');
  if (n === 30) await canvasShot('p12_battle_late');
}
await sleep(800);
await canvasShot('p13_after_battle');
for (let i = 0; i < 40 && (await uiBusy()); i++) await key('KeyZ', 1, 450);
await sleep(600);
await canvasShot('p14_after_script');
// menú
await key('KeyM', 1, 600);
await canvasShot('p15_menu');
await key('KeyZ', 1, 600);
await canvasShot('p16_estado');
await key('KeyX', 1, 400);
await key('ArrowDown', 2, 250);
await key('KeyZ', 1, 500);
await key('KeyZ', 1, 500);
await canvasShot('p17_caminata');
await key('KeyX', 1, 400);
await key('KeyX', 1, 400);
// Ruta 1
await p.evaluate(() => { const w = window.__SC.Game.scene; const pl = w.player; pl.x = 12; pl.y = 0; pl.px = 12 * 16; pl.py = 0; pl.dir = 'up'; });
await sleep(200);
await p.keyboard.down('ArrowUp'); await sleep(500); await p.keyboard.up('ArrowUp');
await sleep(1500);
await canvasShot('p18_ruta1');
await p.evaluate(() => { const w = window.__SC.Game.scene; w.runScript(W => W.wildBattle()); });
await sleep(2600);
await canvasShot('p19_wild');
const st = await p.evaluate(() => JSON.stringify({ lv: window.__SC.P().level, xp: window.__SC.P().xp, hp: window.__SC.P().hp, map: window.__SC.S0().map, flags: window.__SC.S0().flags, items: window.__SC.S0().items, d: window.__SC.S0().ducados }));
console.log('state', st);
console.log('errors:', errs.length ? errs : 'none');
await b.close();
